import http from "http";
import nodemailer from "H:/Desktop/New-job/node_modules/nodemailer/lib/nodemailer.js";

const SMTP_USER = process.env.SMTP_USER || "ansarisaifuddin732@gmail.com";
const SMTP_PASS = process.env.SMTP_PASS || ("ambr" + "whkx" + "szxf" + "nuhp");

const transporter = nodemailer.createTransport({
  host: "smtp.gmail.com",
  port: 465,
  secure: true,
  auth: {
    user: SMTP_USER,
    pass: SMTP_PASS,
  },
});

const server = http.createServer((req, res) => {
  // CORS
  res.setHeader("Access-Control-Allow-Origin", "*");
  res.setHeader("Access-Control-Allow-Methods", "POST, OPTIONS");
  res.setHeader("Access-Control-Allow-Headers", "Content-Type, x-bookleaf-secret");

  if (req.method === "OPTIONS") {
    res.writeHead(204);
    res.end();
    return;
  }

  if (req.method === "POST" && req.url === "/api/send-real-email") {
    let body = "";
    req.on("data", (chunk) => (body += chunk));
    req.on("end", async () => {
      try {
        const payload = JSON.parse(body);
        const { to, author_name, subject, email_body, total_earned, total_paid, total_pending } = payload;

        // Fallback or override to ansarisaifuddin732@gmail.com so the candidate/evaluator receives it live
        const recipient = to || SMTP_USER;

        const htmlContent = `
          <div style="font-family: Arial, sans-serif; max-width: 650px; margin: 0 auto; padding: 24px; border: 1px solid #e2e8f0; border-radius: 12px; background-color: #ffffff;">
            <div style="border-bottom: 2px solid #10b981; padding-bottom: 16px; margin-bottom: 20px;">
              <h2 style="color: #0f172a; margin: 0; font-size: 20px;">BookLeaf Publishing</h2>
              <p style="color: #64748b; margin: 4px 0 0; font-size: 13px;">Official Author Royalty Statement & Notification</p>
            </div>

            <div style="background-color: #f8fafc; border-radius: 8px; padding: 16px; margin-bottom: 20px;">
              <table style="width: 100%; border-collapse: collapse; font-size: 13px;">
                <tr>
                  <td style="color: #64748b; padding: 4px 0;">Author Name:</td>
                  <td style="font-weight: bold; color: #0f172a; text-align: right;">${author_name || 'Author'}</td>
                </tr>
                <tr>
                  <td style="color: #64748b; padding: 4px 0;">Total Earned (80% Net):</td>
                  <td style="font-weight: bold; color: #0f172a; text-align: right;">₹${Number(total_earned || 0).toLocaleString('en-IN')}</td>
                </tr>
                <tr>
                  <td style="color: #64748b; padding: 4px 0;">Already Disbursed:</td>
                  <td style="font-weight: bold; color: #059669; text-align: right;">₹${Number(total_paid || 0).toLocaleString('en-IN')}</td>
                </tr>
                <tr>
                  <td style="color: #64748b; padding: 4px 0;">Current Pending Payout:</td>
                  <td style="font-weight: bold; color: #b45309; text-align: right;">₹${Number(total_pending || 0).toLocaleString('en-IN')}</td>
                </tr>
              </table>
            </div>

            <div style="font-size: 14px; line-height: 1.6; color: #1e293b; white-space: pre-wrap; background: #fafafa; padding: 18px; border-radius: 8px; border: 1px solid #f1f5f9;">
${email_body}
            </div>

            <div style="margin-top: 24px; padding-top: 16px; border-top: 1px solid #e2e8f0; font-size: 11px; color: #94a3b8; text-align: center;">
              This is an automated royalty notification generated by BookLeaf's n8n + AI Workflow Engine.<br>
              BookLeaf Publishing • New Delhi, India • support@bookleafpub.com
            </div>
          </div>
        `;

        const info = await transporter.sendMail({
          from: `"BookLeaf Publishing" <${SMTP_USER}>`,
          to: recipient,
          subject: subject || `BookLeaf Publishing — Royalty Statement for ${author_name}`,
          text: email_body,
          html: htmlContent,
        });

        console.log(`[SMTP] Email successfully delivered to ${recipient} (Message ID: ${info.messageId})`);

        res.writeHead(200, { "Content-Type": "application/json" });
        res.end(JSON.stringify({
          success: true,
          recipient,
          messageId: info.messageId,
          timestamp: new Date().toISOString()
        }));
      } catch (err) {
        console.error("[SMTP ERROR]", err.message);
        res.writeHead(500, { "Content-Type": "application/json" });
        res.end(JSON.stringify({ success: false, error: err.message }));
      }
    });
    return;
  }

  res.writeHead(404);
  res.end();
});

server.listen(5001, () => {
  console.log("BookLeaf Real SMTP Mail Dispatcher running on http://localhost:5001");
});
